#!/usr/bin/env python3
"""Recompute the clinical-stratum Dice tables and the boundary-loss margin ablation.

Run from the repo root:  python tools/make_tables_clinical.py
Joins per-sample test Dice (test_summary_all.json) to nodule_clinical_metadata.json using the
test_keys order in train_val_test_split.json. It first checks that the join reproduces the means in
clinical_stratification_summary.json; if it does not, the ordering assumption is wrong and it stops.
Writes outputs/generated/clinical_tables.md.
"""
import json, os, sys
import numpy as np
from scipy import stats

T, OUT = "outputs/test_results", "outputs/generated"
SEEDS = [42, 123, 456, 789, 2024]
ARCHS = ["unet3d_paper", "unetr"]
CFG = ["baseline", "boundary", "boundary_adaptive"]
LABEL = {"baseline": "baseline", "boundary": "boundary_fixed", "boundary_adaptive": "boundary_adaptive"}
lines = []
def P(s=""):
    lines.append(s); print(s)

split = json.load(open("train_val_test_split.json"))
meta = json.load(open("nodule_clinical_metadata.json"))
R = json.load(open(f"{T}/test_summary_all.json"))["results"]
CLIN = json.load(open(f"{T}/clinical_stratification_summary.json"))
test_keys = split["test_keys"]
assert len(test_keys) == 434, len(test_keys)

def bins():
    f = {
        "texture": ("texture_mean", [("Non-Solid (GGN)", lambda x: x <= 2.0), ("Part-Solid", lambda x: 2.0 < x < 4.0), ("Solid", lambda x: x >= 4.0)]),
        "subtlety": ("subtlety_mean", [("Subtle (<=2.5)", lambda x: x <= 2.5), ("Moderate (2.5-3.5)", lambda x: 2.5 < x <= 3.5), ("Obvious (>3.5)", lambda x: x > 3.5)]),
        "spiculation": ("spiculation_mean", [("Smooth (<=2.0)", lambda x: x <= 2.0), ("Spiculated (>2.0)", lambda x: x > 2.0)]),
        "malignancy": ("malignancy_mean", [("Low Suspicion (<=2.5)", lambda x: x <= 2.5), ("Indeterminate (2.5-3.5)", lambda x: 2.5 < x <= 3.5), ("High Suspicion (>3.5)", lambda x: x > 3.5)]),
    }
    out = {}
    for axis, (field, defs) in f.items():
        for name, fn in defs:
            out[f"{axis}_{name}"] = np.array([fn(meta[k][field]) for k in test_keys])
    return out

B = bins()
def dice(arch, cfg, s):
    return np.array(R[f"{cfg}_{arch}_seed{s}"]["per_sample_dice"], dtype=float)
def stratum(arch, cfg, name):
    m = B[name]
    return np.array([dice(arch, cfg, s)[m].mean() for s in SEEDS])

P("# Clinical-stratum tables (generated by tools/make_tables_clinical.py)\n")
P("## 1. Join check against clinical_stratification_summary.json\n")
bad = 0
P("| Stratum | N (join) | N (summary) | UNet3D mean (join) | (summary) | UNETR mean (join) | (summary) |")
P("|---|---|---|---|---|---|---|")
for name, m in B.items():
    c = CLIN["comparisons"][name]
    a, b = stratum("unet3d_paper", "baseline", name).mean(), stratum("unetr", "baseline", name).mean()
    ok = abs(a - c["mean_a"]) < 1e-6 and abs(b - c["mean_b"]) < 1e-6
    bad += not ok
    P(f"| {name} | {int(m.sum())} | | {a:.4f} | {c['mean_a']:.4f} | {b:.4f} | {c['mean_b']:.4f} |" + ("" if ok else "  **MISMATCH**"))
P()
if bad:
    sys.exit(f"{bad} strata do not reproduce the summary: the test_keys / per_sample_dice ordering assumption is wrong")
P("Join reproduces all 11 strata exactly, so the key ordering assumption holds.\n")

def ptests(x, y):
    t, pt = stats.ttest_rel(x, y)
    try: pw = stats.wilcoxon(x, y).pvalue
    except ValueError: pw = float("nan")
    return t, pt, pw

P("## 2. Boundary loss on margin morphology (Dice, 5 seeds)\n")
P("| Arch | Config | Stratum | baseline | config | diff | t p | Wilcoxon p |")
P("|---|---|---|---|---|---|---|---|")
for arch in ARCHS:
    for cfg in ["boundary", "boundary_adaptive"]:
        for name in ["spiculation_Spiculated (>2.0)", "spiculation_Smooth (<=2.0)"]:
            x, y = stratum(arch, "baseline", name), stratum(arch, cfg, name)
            t, pt, pw = ptests(x, y)
            P(f"| {arch} | {LABEL[cfg]} | {name.split('_')[1]} | {x.mean():.4f} ± {x.std():.4f} | {y.mean():.4f} ± {y.std():.4f} | {y.mean()-x.mean():+.4f} | {pt:.4f} | {pw:.4f} |")
P()

P("## 3. Exploratory: every stratum, boundary vs baseline (Dice), both architectures\n")
P("Exploratory only: 11 strata x 2 configs x 2 architectures = 44 tests, uncorrected.\n")
P("| Arch | Config | Stratum | diff | t p | Wilcoxon p |")
P("|---|---|---|---|---|---|")
rows = []
for arch in ARCHS:
    for cfg in ["boundary", "boundary_adaptive"]:
        for name in B:
            x, y = stratum(arch, "baseline", name), stratum(arch, cfg, name)
            t, pt, pw = ptests(x, y)
            rows.append((pt, arch, LABEL[cfg], name, y.mean() - x.mean(), pw))
for pt, arch, cfg, name, d, pw in sorted(rows)[:10]:
    P(f"| {arch} | {cfg} | {name} | {d:+.4f} | {pt:.4f} | {pw:.4f} |")
P(f"\n(smallest 10 of {len(rows)} shown; with alpha = 0.05/{len(rows)} = {0.05/len(rows):.5f} the number surviving is {sum(r[0] < 0.05/len(rows) for r in rows)})\n")

os.makedirs(OUT, exist_ok=True)
open(f"{OUT}/clinical_tables.md", "w").write("\n".join(lines) + "\n")
print(f"[written to {OUT}/clinical_tables.md]")
