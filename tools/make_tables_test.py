#!/usr/bin/env python3
"""Recompute every held-out-test number from the raw JSONs.

Run from the repo root:
    python tools/make_tables_test.py
Writes outputs/generated/test_tables.md and prints it. Needs numpy and scipy.
Reads: outputs/test_results/{test_summary_all,test_nsd_summary,clinical_stratification_summary,
architecture_comparison_summary}.json and outputs/results/*.json (validation side, for the val-to-test gap).
All +/- values are population SD (ddof=0).
"""
import json, os, sys
import numpy as np
from scipy import stats

T = "outputs/test_results"
RES = "outputs/results"
OUT = "outputs/generated"
ARCHS = ["unet3d_paper", "unetr"]
CONFIGS = ["baseline", "boundary", "boundary_adaptive"]
LABEL = {"baseline": "baseline", "boundary": "boundary_fixed", "boundary_adaptive": "boundary_adaptive"}
SEEDS = [42, 123, 456, 789, 2024]
METRICS = ["dice", "iou", "hd95", "assd", "nsd_1mm", "nsd_2mm"]
TIERS = ["small", "medium", "large"]

lines = []
def P(s=""):
    lines.append(s); print(s)

def load(name):
    p = os.path.join(T, name)
    if not os.path.exists(p):
        sys.exit(f"missing {p} (run from the repo root)")
    return json.load(open(p))

R = load("test_summary_all.json")["results"]
NSD = load("test_nsd_summary.json")
CLIN = load("clinical_stratification_summary.json")
ARCH = load("architecture_comparison_summary.json")

def metric(arch, cfg, s, m):
    if m.startswith("nsd"):
        return NSD[arch][cfg][str(s)][m]
    return R[f"{cfg}_{arch}_seed{s}"][m]

def arr(arch, cfg, m):
    return np.array([metric(arch, cfg, s, m) for s in SEEDS], dtype=float)

def tier(arch, cfg, t):
    return np.array([R[f"{cfg}_{arch}_seed{s}"]["size_stratified"][t]["mean"] for s in SEEDS], dtype=float)

def msd(x, nd=4):
    return f"{np.mean(x):.{nd}f} ± {np.std(x):.{nd}f}"

def ptests(a, b):
    t, pt = stats.ttest_rel(a, b)
    try:
        pw = stats.wilcoxon(a, b).pvalue
    except ValueError:
        pw = float("nan")
    return t, pt, pw

def val_last10(arch, cfg, key="val_dice_mean_last10"):
    return np.array([json.load(open(f"{RES}/{cfg}_{arch}_seed{s}.json"))[key] for s in SEEDS], dtype=float)

family = []   # (family_tag, label, t-test p)

# ------------------------------------------------------------------
P("# Held-out test tables (generated by tools/make_tables_test.py)\n")

P("## 1. Inventory\n")
for a in ARCHS:
    for c in CONFIGS:
        n = [R[f"{c}_{a}_seed{s}"]["n_test_samples"] for s in SEEDS]
        sk = [R[f"{c}_{a}_seed{s}"]["hd95_skipped"] for s in SEEDS]
        P(f"- {a} / {LABEL[c]}: n_test_samples {set(n)}; hd95_skipped per seed {sk}")
P()

P("## 2. Test metrics (mean ± SD over 5 seeds)\n")
for a in ARCHS:
    P(f"### {a}\n")
    P("| Config | Dice | IoU | HD95 (mm) | ASSD (mm) | NSD@1mm | NSD@2mm |")
    P("|---|---|---|---|---|---|---|")
    for c in CONFIGS:
        P(f"| {LABEL[c]} | " + " | ".join(msd(arr(a, c, m)) for m in METRICS) + " |")
    P()

P("## 3. Full-cohort boundary-vs-baseline tests\n")
P("| Arch | Config | Metric | baseline | config | diff | t p | Wilcoxon p |")
P("|---|---|---|---|---|---|---|---|")
for a in ARCHS:
    for c in ["boundary", "boundary_adaptive"]:
        for m in METRICS:
            x, y = arr(a, "baseline", m), arr(a, c, m)
            t, pt, pw = ptests(x, y)
            P(f"| {a} | {LABEL[c]} | {m} | {x.mean():.4f} | {y.mean():.4f} | {y.mean()-x.mean():+.4f} | {pt:.4f} | {pw:.4f} |")
            family.append(("full", f"{a}/{LABEL[c]}/{m}", pt))
P()
allp = sorted(((p, l) for f, l, p in family if f == "full"))[:3]
P(f"Smallest three full-cohort t-test p-values: {[(l, round(p,4)) for p, l in allp]}\n")

P("## 4. Volume tiers (small < 100 vx, medium 100-500, large > 500)\n")
ns = {t: R[f"baseline_unet3d_paper_seed42"]["size_stratified"][t]["n"] for t in TIERS}
P(f"Tier sizes: {ns}\n")
P("| Arch | Config | Small | Medium | Large |")
P("|---|---|---|---|---|")
for a in ARCHS:
    for c in CONFIGS:
        P(f"| {a} | {LABEL[c]} | " + " | ".join(msd(tier(a, c, t)) for t in TIERS) + " |")
P()
P("| Arch | Config | Tier | baseline | config | diff | t | t p | Wilcoxon p |")
P("|---|---|---|---|---|---|---|---|---|")
tier_p = []
for a in ARCHS:
    for c in ["boundary", "boundary_adaptive"]:
        for t in TIERS:
            x, y = tier(a, "baseline", t), tier(a, c, t)
            tt, pt, pw = ptests(x, y)
            tier_p.append((pt, a, LABEL[c], t))
            family.append(("tier", f"{a}/{LABEL[c]}/{t}", pt))
            P(f"| {a} | {LABEL[c]} | {t} | {x.mean():.4f} | {y.mean():.4f} | {y.mean()-x.mean():+.4f} | {tt:.3f} | {pt:.5f} | {pw:.4f} |")
P()

P("## 5. Multiple-comparison families\n")
a12 = 0.05 / 12
rep13 = [("unet3d_paper", "boundary", m) for m in ["dice", "hd95", "assd", "nsd_1mm", "nsd_2mm"]] + \
        [("unet3d_paper", "boundary_adaptive", m) for m in ["dice", "hd95"]] + \
        [("unetr", "boundary", m) for m in ["dice", "hd95", "assd", "nsd_1mm", "nsd_2mm"]] + \
        [("unetr", "boundary_adaptive", "dice")]
K_rep = 12 + len(rep13) + 3
K_full = 12 + 4 * 6 + 3   # all 6 metrics x 2 configs x 2 archs, plus the 3 margin tests
P(f"- Volume-stratified family: K = 12, alpha = {a12:.5f}")
P(f"- Reported-comparison family: 12 tiers + {len(rep13)} full-cohort + 3 margin = K = {K_rep}, alpha = {0.05/K_rep:.5f}")
P(f"- Full family (all 6 metrics for both configs on both architectures + 12 tiers + 3 margin): K = {K_full}, alpha = {0.05/K_full:.5f}\n")
P("| Comparison | t p | survives K=12 | survives K=28 | survives full K |")
P("|---|---|---|---|---|")
for pt, a, c, t in sorted(tier_p)[:4]:
    P(f"| {a}/{c}/{t} | {pt:.5f} | {pt < a12} | {pt < 0.05/K_rep} | {pt < 0.05/K_full} |")
P()

P("## 6. Architecture comparison (UNet3DPaper minus UNETR)\n")
a_d = np.array([arr("unet3d_paper", c, "dice") for c in CONFIGS]).ravel()
b_d = np.array([arr("unetr", c, "dice") for c in CONFIGS]).ravel()
diff = a_d - b_d
t, pt, pw = ptests(a_d, b_d)
d_paired = diff.mean() / diff.std(ddof=1) if False else diff.mean() / diff.std()
P(f"- Pooled Dice: UNet3DPaper {a_d.mean():.4f} ± {a_d.std():.4f}, UNETR {b_d.mean():.4f} ± {b_d.std():.4f}")
P(f"- **Pooled gap: {100*(a_d.mean()-b_d.mean()):.2f} Dice points** (per-pair range {100*diff.min():.2f} to {100*diff.max():.2f}); t p = {pt:.2e}, Wilcoxon p = {pw:.2e}, paired d = {d_paired:.2f}")
for c in CONFIGS:
    g = arr("unet3d_paper", c, "dice").mean() - arr("unetr", c, "dice").mean()
    P(f"- {LABEL[c]}: gap {100*g:.2f} Dice points")
a_h = np.array([arr("unet3d_paper", c, "hd95") for c in CONFIGS]).ravel()
b_h = np.array([arr("unetr", c, "hd95") for c in CONFIGS]).ravel()
P(f"- Pooled HD95: {a_h.mean():.4f} vs {b_h.mean():.4f}, gap {b_h.mean()-a_h.mean():.2f} mm")
for m in ["nsd_1mm", "nsd_2mm"]:
    a_m = np.array([arr("unet3d_paper", c, m) for c in CONFIGS]).ravel()
    b_m = np.array([arr("unetr", c, m) for c in CONFIGS]).ravel()
    P(f"- Pooled {m}: {a_m.mean():.4f} vs {b_m.mean():.4f}")
chk = ARCH["pooled"]["dice"]
P(f"- Check against architecture_comparison_summary.json: pooled mean_a {chk['mean_a']:.4f}, mean_b {chk['mean_b']:.4f}, gap {100*(chk['mean_a']-chk['mean_b']):.2f}")
P()

P("## 7. Validation-to-test gap\n")
P("| Arch | Config | test Dice | val last-10 Dice | gap (last-10) | val best Dice | gap (best) |")
P("|---|---|---|---|---|---|---|")
for a in ARCHS:
    for c in CONFIGS:
        td = arr(a, c, "dice")
        v10, vb = val_last10(a, c), val_last10(a, c, "best_val_dice")
        P(f"| {a} | {LABEL[c]} | {td.mean():.4f} | {v10.mean():.4f} | {td.mean()-v10.mean():+.4f} | {vb.mean():.4f} | {td.mean()-vb.mean():+.4f} |")
P()
P("| Arch | Config | HD95 gap (last-10) | ASSD note |")
P("|---|---|---|---|")
for a in ARCHS:
    for c in CONFIGS:
        P(f"| {a} | {LABEL[c]} | {arr(a,c,'hd95').mean()-val_last10(a,c,'val_hd95_mean_last10').mean():+.2f} mm | |")
P()

P("## 8. UNETR adaptive vs baseline, per seed (gate activated only for seed 2024)\n")
P("| Seed | baseline Dice | adaptive Dice | diff |")
P("|---|---|---|---|")
bd, ad = arr("unetr", "baseline", "dice"), arr("unetr", "boundary_adaptive", "dice")
for s, x, y in zip(SEEDS, bd, ad):
    P(f"| {s} | {x:.4f} | {y:.4f} | {y-x:+.4f} |")
inact = [i for i, s in enumerate(SEEDS) if s != 2024]
dd = (ad - bd)[inact]
P(f"\nMean difference over the four never-activated seeds (42, 123, 456, 789): {dd.mean():+.4f} ± {dd.std():.4f}; seed 2024: {(ad-bd)[SEEDS.index(2024)]:+.4f}\n")
allr = np.concatenate([arr("unetr", c, "dice") for c in CONFIGS])
P(f"UNETR per-run test Dice range over 15 runs: {allr.min():.4f} to {allr.max():.4f}\n")

P("## 9. Clinical strata (baseline config, from clinical_stratification_summary.json)\n")
P("| Stratum | N | UNet3DPaper | UNETR | Cohen's d | t p | Wilcoxon p |")
P("|---|---|---|---|---|---|---|")
counts = {}
for ax, d in CLIN["bin_counts"].items():
    for k, v in d.items():
        counts[f"{ax}_{k}"] = v
for k, v in CLIN["comparisons"].items():
    P(f"| {k} | {counts.get(k, '?')} | {v['mean_a']:.4f} ± {v['std_a']:.4f} | {v['mean_b']:.4f} ± {v['std_b']:.4f} | {v['cohens_d']:+.2f} | {v['t_p']:.2e} | {v['w_p']:.4f} |")
P("\n(The spiculated/smooth boundary-loss ablation needs per-sample Dice joined to nodule_clinical_metadata.json; it is not in this summary file.)\n")

os.makedirs(OUT, exist_ok=True)
open(f"{OUT}/test_tables.md", "w").write("\n".join(lines) + "\n")
print(f"[written to {OUT}/test_tables.md]")
